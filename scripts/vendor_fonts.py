#!/usr/bin/env python3
"""Vendor the dashboard's web fonts from pinned Fontsource npm packages.

Instances serve their fonts from ``/static`` so no page asks a third party (eg Google Fonts) for them. This
downloads each pinned package, checks it against the registry's integrity hash, and regenerates
``static/fonts/`` and ``static/css/fonts.css``. To bump a font, change its version and integrity below and rerun:

    pixi run -e dev python scripts/vendor_fonts.py
"""

from __future__ import annotations

import base64
import hashlib
import io
import re
import shutil
import tarfile
import urllib.request
from pathlib import Path

import attr

STATIC_DIR = Path(__file__).resolve().parent.parent / "compute_space" / "src" / "compute_space" / "web" / "static"
FONTS_DIR = STATIC_DIR / "fonts"
FONTS_CSS = STATIC_DIR / "css" / "fonts.css"
# Keep in sync with --weight-regular / --weight-emphasized in tokens.css.
WEIGHTS = (400, 500)
_SRC = re.compile(r"src: url\(\./files/(?P<name>[\w.-]+\.woff2)\) format\('woff2'\)(?:, url\([^)]*\) format\('woff'\))?;")


@attr.s(auto_attribs=True, frozen=True)
class FontPackage:
    name: str
    version: str
    integrity: str

    @property
    def dir_name(self) -> str:
        # Versioned so a bump changes every font URL; the font files themselves aren't cache-busted.
        return f"{self.name}-{self.version}"


PACKAGES = (
    FontPackage(
        name="inter",
        version="5.3.0",
        integrity="sha512-RofMylZmjlJEfELXeNHFWBRcSs75rGU/6bV2S2jfnvv/3rPXPGe0LgUJTklcHZ9lM4OZmAVFhcJPnACfb91A3g==",
    ),
    FontPackage(
        name="ibm-plex-mono",
        version="5.3.0",
        integrity="sha512-eTgnZjZEGk1QtD3ZstF+Vclo2HLAni8YMy34/DxllwZvyz1lR/1RF/xTiAquOBO7MvqBx8D2Ig2WCPMVfdZu7Q==",
    ),
)


def _download(package: FontPackage) -> tarfile.TarFile:
    url = f"https://registry.npmjs.org/@fontsource/{package.name}/-/{package.name}-{package.version}.tgz"
    with urllib.request.urlopen(url) as response:
        data = response.read()
    algorithm, expected = package.integrity.split("-", 1)
    actual = base64.b64encode(hashlib.new(algorithm, data).digest()).decode("ascii")
    if actual != expected:
        raise SystemExit(f"{url}: integrity mismatch (expected {expected}, got {actual})")
    return tarfile.open(fileobj=io.BytesIO(data), mode="r:gz")


def _read(archive: tarfile.TarFile, path: str) -> bytes:
    member = archive.extractfile(f"package/{path}")
    if member is None:
        raise SystemExit(f"package/{path} is not a regular file")
    return member.read()


def _vendor(package: FontPackage) -> str:
    """Copy one package's woff2 files and license into place and return its @font-face rules."""
    out_dir = FONTS_DIR / package.dir_name
    out_dir.mkdir(parents=True)
    rules = []
    with _download(package) as archive:
        (out_dir / "LICENSE").write_bytes(_read(archive, "LICENSE"))
        for weight in WEIGHTS:
            css = _read(archive, f"{weight}.css").decode("utf-8")
            for match in _SRC.finditer(css):
                (out_dir / match["name"]).write_bytes(_read(archive, f"files/{match['name']}"))
            # Absolute URLs, so the rules also work when setup_app inlines this file into a page.
            rules.append(
                _SRC.sub(
                    lambda m: f'src: url("/static/fonts/{package.dir_name}/{m["name"]}") format("woff2");',
                    css,
                ).strip()
            )
    if not any(out_dir.glob("*.woff2")):
        raise SystemExit(f"{package.name}: no woff2 files matched; has the Fontsource CSS format changed?")
    license_note = f"SIL OFL 1.1, see ../fonts/{package.dir_name}/LICENSE"
    return f"/* @fontsource/{package.name}@{package.version} ({license_note}) */\n" + "\n\n".join(rules)


def main() -> None:
    shutil.rmtree(FONTS_DIR, ignore_errors=True)
    sections = [_vendor(package) for package in PACKAGES]
    header = "/* Generated by scripts/vendor_fonts.py; edit that script, not this file. */\n\n"
    FONTS_CSS.write_text(header + "\n\n".join(sections) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
